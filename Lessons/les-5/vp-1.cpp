#include <iostream>
using namespace std;
int main() {
  int a, *p, x;
  cin >> a >> x;
  cout << a << " <- значення змінної a ||| адреса змінної a -> " << &a << endl;
  p = &a;
  cout << p << " <- Вказівник р ||| адреса вказівника -> " << &p << endl;
  cout << *p
       << " <- значення змінної а за допомогою вказівника p ||| адреса "
          "значення змінної а за допомогою вказівника -> "
       << &(*p) << endl;
  p = &x;
  cout << x << " <- значення змінної x ||| адреса змінної x -> " << &x << endl;
  cout << p << " <- Вказівник р ||| адреса вказівника -> " << &p << endl;
  cout << *p
       << " <- значення змінної х за допомогою вказівника p ||| адреса "
          "значення змінної х за допомогою вказівника -> "
       << &(*p) << endl;
  p = nullptr;

  return 0;
}