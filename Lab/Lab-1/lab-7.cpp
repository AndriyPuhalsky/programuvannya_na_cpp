#include <iostream>

using namespace std;

int main() {
  int K;

  cout << "Введіть номер дня року K (від 1 до 365): ";
  cin >> K;

  if (K < 1 || K > 365) {
    cout << "Помилка: K повинно бути в межах від 1 до 365." << endl;
    return 1;
  }

  // Загальна формула для будь-якого стартового дня D: (K + D - 2) % 7 + 1 ,
  // тому що стартовий день вівторок.
  // Підставляємо D = 2: (K + 2 - 2) % 7 + 1 =
  // (K % 7) + 1
  int day_of_week = (K % 7) + 1;

  cout << "Номер дня тижня для " << K << "-го дня року: " << day_of_week
       << endl;

  return 0;
}
